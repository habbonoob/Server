using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Habbo.Protocol.Generator;

/// <summary>Emits the writer for one message or struct. The output is deliberately plain —
/// it is meant to be readable when someone steps into it.</summary>
internal static class WireEmitter
{
    public static string Emit(
        WireType_Model model, HashSet<string> readable, HashSet<string> varying, Dictionary<string, int> structWidths)
    {
        if (model.IsIncoming)
            return EmitReader(model, structWidths);

        var text = new StringBuilder();
        text.AppendLine("// <auto-generated/> Written by Habbo.Protocol.Generator from the type's wire layout.");
        text.AppendLine("#nullable enable");
        text.AppendLine();
        text.AppendLine("using Habbo.Protocol.IO;");
        text.AppendLine();

        // A [WireWhen] member is nullable because the condition decides whether it is written,
        // not because null is a legal value under a true condition. Writing nothing there would
        // desync the packet, so the dereference is meant to throw instead.
        if (model.Fields.Any(f => f.Condition is not null))
        {
            text.AppendLine("#pragma warning disable CS8602, CS8604, CS8629 " +
                            "// a [WireWhen] value must be present when its condition holds");
            text.AppendLine();
        }

        if (!string.IsNullOrEmpty(model.Namespace))
        {
            text.AppendLine($"namespace {model.Namespace};");
            text.AppendLine();
        }

        var isMessage = model.HeaderExpression is not null;
        text.AppendLine($"partial record {model.TypeName}{(isMessage ? " : Habbo.Protocol.Composers.IComposer" : "")}");
        text.AppendLine("{");

        if (isMessage)
        {
            text.AppendLine($"    public ushort Header => {model.HeaderExpression};");
            text.AppendLine();
            if (varying.Contains(model.FullName))
            {
                text.AppendLine("    /// <summary>Client releases lay this message out differently.</summary>");
                text.AppendLine("    public bool VariesByRelease => true;");
                text.AppendLine();
            }

            text.AppendLine("    public void Compose(MessageWriter w)");
        }
        else
        {
            text.AppendLine("    /// <summary>Writes this struct inline, at the current position.</summary>");
            text.AppendLine("    public void Write(MessageWriter w)");
        }

        text.AppendLine("    {");
        EmitFields(text, model, "        ");
        text.AppendLine("    }");

        // A struct whose every member can be read back is read too, for incoming messages that carry it.
        if (!isMessage && readable.Contains(model.FullName))
        {
            text.AppendLine();
            text.AppendLine("    /// <summary>Reads this struct inline, at the current position.</summary>");
            EmitSequentialRead(text, model);
            EmitListReaders(text, model, structWidths);
        }

        text.AppendLine("}");

        return text.ToString();
    }

    /// <summary>An incoming message is a flat sequence of fields, so the reader is the
    /// constructor called with one read per parameter, in order.</summary>
    private static string EmitReader(WireType_Model model, Dictionary<string, int> structWidths)
    {
        var text = new StringBuilder();
        text.AppendLine("// <auto-generated/> Written by Habbo.Protocol.Generator from the type's wire layout.");
        text.AppendLine("#nullable enable");
        text.AppendLine();
        text.AppendLine("using Habbo.Protocol.IO;");
        text.AppendLine();

        if (!string.IsNullOrEmpty(model.Namespace))
        {
            text.AppendLine($"namespace {model.Namespace};");
            text.AppendLine();
        }

        text.AppendLine($"partial record {model.TypeName} : Habbo.Protocol.Messages.IIncomingMessage<{model.TypeName}>");
        text.AppendLine("{");
        text.AppendLine($"    public static ushort Header => {model.HeaderExpression};");
        text.AppendLine();
        if (model.Fields.Count == 0)
        {
            text.AppendLine($"    public static {model.TypeName} Read(MessageReader r)");
            text.AppendLine("    {");
            text.AppendLine("        // no fields on the wire");
            text.AppendLine("        return new();");
            text.AppendLine("    }");
        }
        else
        {
            EmitSequentialRead(text, model);
        }

        EmitListReaders(text, model, structWidths);

        text.AppendLine("}");
        return text.ToString();
    }

    /// <summary>Whether a field is one value read and written as-is: what a readable struct holds.</summary>
    private static bool IsPlainField(WireField field) =>
        field.Kind == FieldKind.Primitive && field.Condition is null && field.FlagBit is null && !field.Optional
        && field.Type is WireType.I32 or WireType.I16 or WireType.U8 or WireType.Bool or WireType.Utf8
            or WireType.F32 or WireType.I64 or WireType.F64;

    /// <summary>A helper per list field. The reader is one constructor call, which has nowhere
    /// to put a loop, so each list is read by a method the call invokes in argument order.</summary>
    private static void EmitListReaders(StringBuilder text, WireType_Model model, Dictionary<string, int> structWidths)
    {
        foreach (var field in model.Fields.Where(f => f.Kind == FieldKind.List))
        {
            var element = field.ElementIsStruct ? StructName(field) : ElementTypeName(field.Type);
            var read = field.ElementIsStruct ? $"{StructName(field)}.Read(r)" : PrimitiveRead(field.Type);
            var width = !field.ElementIsStruct ? MinimumWidth(field.Type)
                : structWidths.TryGetValue(field.StructTypeName!.TrimEnd('?'), out var structWidth) ? System.Math.Max(1, structWidth)
                : 1;

            text.AppendLine();
            text.AppendLine($"    private static IReadOnlyList<{element}> Read{field.Name}(MessageReader r)");
            text.AppendLine("    {");
            text.AppendLine($"        var count = {CountRead(field.CountType)};");
            // every element takes at least its minimum width, so a count past what is left is a lie, refused before
            // it sizes the list; and a list of nested lists is sized as it fills, not all up front from its counts
            text.AppendLine($"        if (count > r.Remaining / {width})");
            text.AppendLine($"            throw new global::System.IO.InvalidDataException($\"{model.TypeName}.{field.Name}: {{count}} elements in {{r.Remaining}} bytes\");");
            text.AppendLine($"        var items = new List<{element}>(Math.Min(Math.Max(0, (int)count), 256));");
            text.AppendLine();
            text.AppendLine("        for (var i = 0; i < count; i++)");
            text.AppendLine($"            items.Add({read});");
            text.AppendLine();
            text.AppendLine("        return items;");
            text.AppendLine("    }");
        }
    }

    /// <summary>A list's count is an int unless the client writes it narrower.</summary>
    private static string CountRead(WireType type) => type switch
    {
        WireType.U8 => "r.ReadByte()",
        WireType.I16 => "r.ReadShort()",
        _ => "r.ReadInt()",
    };

    private static string ElementTypeName(WireType type) => type switch
    {
        WireType.I16 => "short",
        WireType.U8 => "byte",
        WireType.Bool => "bool",
        WireType.Utf8 => "string",
        WireType.F32 => "float",
        WireType.I64 => "long",
        WireType.F64 => "double",
        _ => "int",
    };

    /// <summary>Reads the members one at a time, in wire order, into a value that starts empty. A member behind a
    /// [WireWhen] is read only when its condition holds on what has been read so far, which is how the client's own
    /// parser decides; one with [WirePresence] only when the bool in front of it says it is there; an optional
    /// trailing one only if the client bothered to send it, mirroring its parsers' bytesAvailable checks.</summary>
    private static void EmitSequentialRead(StringBuilder text, WireType_Model model)
    {
        text.AppendLine($"    public static {model.TypeName} Read(MessageReader r)");
        text.AppendLine("    {");
        var empties = string.Join(", ", model.Fields.Select(f => $"default({f.DeclaredType})!"));
        text.AppendLine($"        var value = new {model.TypeName}({empties});");

        foreach (var field in model.Fields)
        {
            var assign = $"value = value with {{ {field.Name} = {ReadExpression(field)} }};";
            var read = field.Condition is not null ? $"if (value.{field.Condition}) {assign}"
                : field.Presence ? $"if (r.ReadBoolean()) {assign}"
                : field.Optional ? $"if (r.Remaining >= {MinimumWidth(field)}) {assign}"
                : assign;

            // a member one release added or dropped is only read from the releases that send it
            text.AppendLine(ReleaseGate(field, "r") is { } release
                ? $"        if ({release}) {{ {read} }}"
                : $"        {read}");
        }

        text.AppendLine("        return value;");
        text.AppendLine("    }");
    }

    /// <summary>The read of one member's value, whatever gates it.</summary>
    private static string ReadExpression(WireField field) => field.Kind switch
    {
        FieldKind.List => $"Read{field.Name}(r)",
        FieldKind.Struct => $"{StructName(field)}.Read(r)",
        _ when field.EnumTypeName is { } enumType => $"({enumType}){PrimitiveRead(field.Type)}",
        _ => PrimitiveRead(field.Type),
    };

    private static string StructName(WireField field) => "global::" + field.StructTypeName!.TrimEnd('?');

    /// <summary>Whether a member can be read back: no flag mask, no count written elsewhere, and a primitive the client
    /// writes as itself, a readable struct, or a list of either.</summary>
    public static bool IsReadable(WireField field, HashSet<string> readableStructs)
    {
        if (field.FlagBit is not null || field.CountBefore is not null)
            return false;

        return field.Kind switch
        {
            FieldKind.Struct => readableStructs.Contains(field.StructTypeName!.TrimEnd('?')),
            FieldKind.List => field.CountType != WireType.Uncounted && (field.ElementIsStruct
                ? readableStructs.Contains(field.StructTypeName!.TrimEnd('?'))
                : IsReadablePrimitive(field.Type)),
            _ => IsReadablePrimitive(field.Type),
        };
    }

    private static bool IsReadablePrimitive(WireType type) =>
        type is WireType.I32 or WireType.I16 or WireType.U8 or WireType.Bool or WireType.Utf8
            or WireType.F32 or WireType.I64 or WireType.F64;

    private static string PrimitiveRead(WireType type) => type switch
    {
        WireType.I16 => "r.ReadShort()",
        WireType.U8 => "r.ReadByte()",
        WireType.Bool => "r.ReadBoolean()",
        WireType.Utf8 => "r.ReadString()",
        WireType.F32 => "r.ReadFloat()",
        WireType.I64 => "r.ReadLong()",
        WireType.F64 => "r.ReadDouble()",
        _ => "r.ReadInt()",
    };

    /// <summary>The smallest number of bytes a member can occupy: a list at least its count, a struct at least a byte.</summary>
    private static int MinimumWidth(WireField field) =>
        field.Kind == FieldKind.List ? (field.CountType == WireType.Uncounted ? 0 : MinimumWidth(field.CountType))
        : field.Kind == FieldKind.Struct ? 1
        : MinimumWidth(field.Type);

    /// <summary>The smallest number of bytes a struct can be read from: what its members that are always there take,
    /// a nested struct by <paramref name="structWidth"/>.</summary>
    public static int MinimumWidth(WireType_Model model, System.Func<string, int> structWidth) =>
        model.Fields
            .Where(f => f.FlagBit is null && f.Condition is null && !f.Optional && f.Since is null && f.Until is null)
            .Sum(f => f.Presence ? 1   // the bool, when the value is not there
                : f.Kind == FieldKind.Struct ? structWidth(f.StructTypeName!.TrimEnd('?'))
                : MinimumWidth(f));

    /// <summary>The smallest number of bytes a value of this type can occupy.</summary>
    private static int MinimumWidth(WireType type) => type switch
    {
        WireType.U8 or WireType.Bool => 1,
        WireType.I16 => 2,
        WireType.Utf8 => 2,   // the two-byte length prefix, even for an empty string
        WireType.I64 or WireType.F64 => 8,
        _ => 4,
    };

    private static void EmitFields(StringBuilder text, WireType_Model model, string indent)
    {
        var fixedFields = model.Fields.Where(f => f.FlagBit is null).ToList();
        var flagged = model.Fields.Where(f => f.FlagBit is not null).ToList();

        foreach (var field in fixedFields)
        {
            // a list that reads its count earlier has it written in front of the member it names
            foreach (var list in fixedFields.Where(list => list.CountBefore == field.Name))
                if (list.CountType != WireType.Uncounted)
                    text.AppendLine($"{indent}{CountCall(list.CountType, list.Name + ".Count")}");

            // a member one release added or dropped is only written to the releases that read it
            var release = ReleaseGate(field, "w");
            if (release is not null)
            {
                text.AppendLine($"{indent}if ({release})");
                text.AppendLine($"{indent}{{");
                EmitFixedField(text, field, indent + "    ");
                text.AppendLine($"{indent}}}");
            }
            else
            {
                EmitFixedField(text, field, indent);
            }
        }

        EmitFlagged(text, flagged, indent);
    }

    /// <summary>The condition under which a release-gated member is on the wire, on the writer or reader named, or
    /// null when every release has it.</summary>
    private static string? ReleaseGate(WireField field, string io) =>
        field.Since is not null ? $"{io}.IsAtLeast({Quote(field.Since)})"
        : field.Until is not null ? $"!{io}.IsAtLeast({Quote(field.Until)})"
        : null;

    private static string Quote(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    private static void EmitFixedField(StringBuilder text, WireField field, string indent)
    {
        // A condition mirrors a branch the client's own parser takes on a value it has
        // already read; an optional field mirrors its bytesAvailable check.
        if (field.Presence)
            text.AppendLine($"{indent}w.WriteBoolean({field.Name} is not null);");

        var gate = field.Condition ?? (field.Optional || field.Presence ? $"{field.Name} is not null" : null);

        if (gate is not null)
        {
            text.AppendLine($"{indent}if ({gate})");
            text.AppendLine($"{indent}{{");
            EmitField(text, field, Access(field), indent + "    ");
            text.AppendLine($"{indent}}}");
        }
        else
        {
            EmitField(text, field, field.Name, indent);
        }
    }

    private static void EmitFlagged(StringBuilder text, List<WireField> flagged, string indent)
    {
        if (flagged.Count == 0)
            return;

        text.AppendLine();
        text.AppendLine($"{indent}// The client reads one mask, then each present payload in ascending bit order.");
        text.AppendLine($"{indent}var flags = 0;");

        foreach (var field in flagged)
        {
            var condition = field.FlagHasPayload ? $"{field.Name} is not null" : field.Name;
            text.AppendLine($"{indent}if ({condition}) flags |= {field.FlagBit};");
        }

        text.AppendLine($"{indent}w.WriteInt(flags);");

        foreach (var field in flagged.Where(f => f.FlagHasPayload))
        {
            text.AppendLine($"{indent}if ({field.Name} is not null)");
            text.AppendLine($"{indent}{{");
            EmitField(text, field, Access(field), indent + "    ");
            text.AppendLine($"{indent}}}");
        }
    }

    /// <summary>A nullable value type needs .Value once the null check has passed.</summary>
    private static string Access(WireField field) =>
        field.NullableValueType ? field.Name + ".Value" : field.Name;

    private static void EmitField(StringBuilder text, WireField field, string access, string indent)
    {
        switch (field.Kind)
        {
            case FieldKind.Primitive:
                text.AppendLine($"{indent}{WriteCall(field.Type, access)}");
                break;

            case FieldKind.Struct:
                text.AppendLine($"{indent}{access}.Write(w);");
                break;

            case FieldKind.List:
                const string item = "item";
                if (field.CountBefore is null && field.CountType != WireType.Uncounted)
                    text.AppendLine($"{indent}{CountCall(field.CountType, access + ".Count")}");
                text.AppendLine($"{indent}foreach (var {item} in {access})");

                if (field.ElementIsStruct)
                {
                    text.AppendLine($"{indent}    {item}.Write(w);");
                }
                else
                {
                    text.AppendLine($"{indent}    {WriteCall(field.Type, item)}");
                }

                break;
        }
    }

    /// <summary>A list's count is an int unless the client reads it narrower. A narrow count is cast checked: a list
    /// too long for it throws rather than telling the client a wrapped count and leaving the stream out of step.</summary>
    private static string CountCall(WireType type, string access) => type switch
    {
        WireType.U8 => $"w.WriteByte(checked((byte){access}));",
        WireType.I16 => $"w.WriteShort(checked((short){access}));",
        _ => $"w.WriteInt({access});",
    };

    private static string WriteCall(WireType type, string access) => type switch
    {
        WireType.I32 => $"w.WriteInt((int){access});",   // an enum is written as its value
        WireType.I16 => $"w.WriteShort((short){access});",
        WireType.U8 => $"w.WriteByte((byte){access});",
        WireType.Bool => $"w.WriteBoolean({access});",
        WireType.Utf8 => $"w.WriteString({access});",
        WireType.F32 => $"w.WriteFloat((float){access});",
        WireType.I64 => $"w.WriteLong({access});",
        WireType.F64 => $"w.WriteDouble({access});",

        // Values the client reads as text and parses back to a number.
        WireType.HeightString =>
            $"w.WriteString(Habbo.Protocol.Wire.WireFormatting.Height({access}));",
        WireType.IntegerString =>
            $"w.WriteString(Habbo.Protocol.Wire.WireFormatting.Integer({access}));",
        WireType.HexString =>
            $"w.WriteString(Habbo.Protocol.Wire.WireFormatting.Hex({access}));",

        _ => $"w.WriteInt((int){access});",
    };

    /// <summary>The layout as data, for the manifest that the protocol tests diff.</summary>
    public static string Describe(WireType_Model model)
    {
        var text = new StringBuilder();
        text.Append("{");
        text.Append($"\"name\":\"{model.TypeName}\",");
        text.Append($"\"header\":{model.HeaderValue},");
        text.Append("\"fields\":[");
        text.Append(string.Join(",", model.Fields.Select(Describe)));
        text.Append("]}");
        return text.ToString();
    }

    private static string Describe(WireField field)
    {
        var parts = new List<string>
        {
            $"\"name\":\"{field.Name}\"",
            $"\"kind\":\"{field.Kind.ToString().ToLowerInvariant()}\"",
        };

        if (field.Kind == FieldKind.List)
        {
            parts.Add($"\"count\":\"{field.CountType.ToString().ToLowerInvariant()}\"");
            if (field.CountBefore is not null)
                parts.Add($"\"countBefore\":\"{field.CountBefore}\"");
            parts.Add(field.ElementIsStruct
                ? $"\"element\":\"{field.StructTypeName}\""
                : $"\"element\":\"{field.Type.ToString().ToLowerInvariant()}\"");
        }
        else if (field.Kind == FieldKind.Struct)
        {
            parts.Add($"\"struct\":\"{field.StructTypeName}\"");
        }
        else
        {
            parts.Add($"\"type\":\"{field.Type.ToString().ToLowerInvariant()}\"");
        }

        if (field.Optional)
            parts.Add("\"optional\":true");

        if (field.Presence)
            parts.Add("\"presence\":true");

        if (field.Condition is not null)
            parts.Add($"\"when\":\"{field.Condition}\"");

        if (field.Since is not null)
            parts.Add($"\"since\":\"{field.Since}\"");

        if (field.Until is not null)
            parts.Add($"\"until\":\"{field.Until}\"");

        if (field.FlagBit is { } bit)
        {
            parts.Add($"\"flagBit\":{bit}");
            parts.Add($"\"flagPayload\":{(field.FlagHasPayload ? "true" : "false")}");
        }

        return "{" + string.Join(",", parts) + "}";
    }
}
